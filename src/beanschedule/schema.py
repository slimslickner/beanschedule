#: The Beancount custom-directive type every schedule directive uses.
TYPE = "schedule"

_GENERATED_BANNER = "> Generated by `beanschedule docs`. Do not edit by hand.\n"


class ValueKind(StrEnum):
    """The kind of value a directive argument or metadata entry expects."""

    STRING = "string"
    DECIMAL = "decimal"
    INTEGER = "integer"
    DATE = "date"
    BOOLEAN = "boolean"
    RRULE = "rrule"
    AMOUNT = "amount (number and currency)"


class AppliesTo(StrEnum):
    """Where a metadata key may appear."""

    NEW = "new"
    POSTING = "posting"
    SKIP = "skip"
    MOVE = "move"


class Severity(StrEnum):
    """The severity of a diagnostic."""

    ERROR = "error"
    WARNING = "warning"


@dataclass(frozen=True, slots=True)
class PositionalArg:
    """A positional argument of a directive verb.

    Attributes:
        name: The argument's name as shown in documentation.
        kind: The kind of value the argument expects.
        required: Whether the argument must be present.
        description: A one-line description of the argument.
    """

    name: str
    kind: ValueKind
    required: bool
    description: str


@dataclass(frozen=True, slots=True)
class DirectiveVerb:
    """A ``custom "schedule"`` verb.

    Attributes:
        verb: The first value of the directive.
        positionals: The positional arguments that follow the verb.
        metadata: The metadata keys allowed on the directive.
        description: A one-line description of the verb.
    """

    verb: str
    positionals: tuple[PositionalArg, ...]
    metadata: tuple[str, ...]
    description: str


@dataclass(frozen=True, slots=True)
class MetadataKey:
    """A metadata key understood by the engine.

    Attributes:
        key: The metadata key, as written in the ledger.
        kind: The kind of value the key expects.
        required: Whether the key must be present where it applies.
        default: The default value, or ``None`` when there is no default.
        applies_to: The verbs the key may appear on.
        description: A one-line description followed by its meaning.
    """

    key: str
    kind: ValueKind
    required: bool
    default: str | None
    applies_to: tuple[AppliesTo, ...]
    description: str


@dataclass(frozen=True, slots=True)
class ReservedValue:
    """A reserved string value with special meaning.

    Attributes:
        value: The reserved value, as written in the ledger.
        meaning: The metadata key the value belongs to.
        description: A one-line description of its effect.
    """

    value: str
    meaning: str
    description: str


@dataclass(frozen=True, slots=True)
class DiagnosticCode:
    """A validation error or warning.

    Attributes:
        code: The stable code, such as ``E001`` or ``W001``.
        severity: Whether the code is an error or a warning.
        summary: A message template with ``str.format`` placeholders.
        explanation: A longer explanation that includes the fix.
    """

    code: str
    severity: Severity
    summary: str
    explanation: str


