"""The single source of truth for schedule metadata and diagnostics.

Three registries live here:

* the **metadata registry**, describing every metadata key the engine
  understands and where it applies,
* the **reserved-value registry**, describing the string values with special
  meaning, and
* the **diagnostic registry**, describing every error and warning code the
  engine can emit.

Parsing, validation and the generated documentation all read these registries,
so the documentation cannot drift from behaviour.
"""

