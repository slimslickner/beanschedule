#: The Beancount custom-directive type a schedule once used. Kept for the
#: legacy-value checks in the migration path.
TYPE = "schedule"

_GENERATED_BANNER = "> Generated by `beanschedule docs`. Do not edit by hand.\n"


class ValueKind(StrEnum):
    """The kind of value a metadata entry expects."""

    STRING = "string"
    DECIMAL = "decimal"
    INTEGER = "integer"
    DATE = "date"
    BOOLEAN = "boolean"
    RRULE = "rrule"


class AppliesTo(StrEnum):
    """Where a metadata key may appear."""

    SCHEDULE = "schedule"
    POSTING = "posting"


class Severity(StrEnum):
    """The severity of a diagnostic."""

    ERROR = "error"
    WARNING = "warning"


@dataclass(frozen=True, slots=True)
class MetadataKey:
    """A metadata key understood by the engine.

    Attributes:
        key: The metadata key, as written in the ledger.
        kind: The kind of value the key expects.
        required: Whether the key must be present where it applies.
        default: The default value, or ``None`` when there is no default.
        applies_to: Where the key may appear.
        description: A one-line description followed by its meaning.
    """

    key: str
    kind: ValueKind
    required: bool
    default: str | None
    applies_to: tuple[AppliesTo, ...]
    description: str


@dataclass(frozen=True, slots=True)
class ReservedValue:
    """A reserved string value with special meaning.

    Attributes:
        value: The reserved value, as written in the ledger.
        meaning: The metadata key the value belongs to.
        description: A one-line description of its effect.
    """

    value: str
    meaning: str
    description: str


@dataclass(frozen=True, slots=True)
class DiagnosticCode:
    """A validation error or warning.

    Attributes:
        code: The stable code, such as ``E001`` or ``W001``.
        severity: Whether the code is an error or a warning.
        summary: A message template with ``str.format`` placeholders.
        explanation: A longer explanation that includes the fix.
    """

    code: str
    severity: Severity
    summary: str
    explanation: str


# --- Metadata registry ---------------------------------------------------------


def _key(
    key: str,
    kind: ValueKind,
    description: str,
    *,
    required: bool = False,
    default: str | None = None,
    applies_to: tuple[AppliesTo, ...] = (AppliesTo.SCHEDULE,),
) -> MetadataKey:
    """Build a :class:`MetadataKey` with the common defaults.

    Args:
        key: The metadata key.
        kind: The kind of value it expects.
        description: Its one-line description and meaning.
        required: Whether it is required.
        default: Its default value, if any.
        applies_to: Where it may appear.

    Returns:
        The constructed :class:`MetadataKey`.
    """
    return MetadataKey(
        key=key,
        kind=kind,
        required=required,
        default=default,
        applies_to=applies_to,
        description=description,
    )


