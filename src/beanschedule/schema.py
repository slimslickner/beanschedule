# --- Metadata registry ---------------------------------------------------------


def _key(
    key: str,
    kind: ValueKind,
    description: str,
    *,
    required: bool = False,
    default: str | None = None,
    applies_to: tuple[AppliesTo, ...] = (AppliesTo.NEW,),
) -> MetadataKey:
    """Build a :class:`MetadataKey` with the common defaults.

    Args:
        key: The metadata key.
        kind: The kind of value it expects.
        description: Its one-line description and meaning.
        required: Whether it is required.
        default: Its default value, if any.
        applies_to: The verbs it may appear on.

    Returns:
        The constructed :class:`MetadataKey`.
    """
    return MetadataKey(
        key=key,
        kind=kind,
        required=required,
        default=default,
        applies_to=applies_to,
        description=description,
    )


